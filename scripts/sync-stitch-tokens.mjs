#!/usr/bin/env node
// Regenerates src/theme/tokens.generated.ts from the archived Stitch screens.
//
// Source of truth is the Tailwind config embedded in each exported screen
// (design/stitch/screens/*/index.html). Screens can diverge, so the config
// shared by the most screens wins and the outliers are listed in the output.
//
// Usage: node scripts/sync-stitch-tokens.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const screensDir = join(root, 'design/stitch/screens');
const outFile = join(root, 'src/theme/tokens.generated.ts');

const REM = 16;
// Tailwind v3 defaults for keys the Stitch config does not override.
const TAILWIND_RADIUS = { none: '0px', xs: '0.125rem', sm: '0.125rem', md: '0.375rem', '2xl': '1rem', '3xl': '1.5rem' };

function extractConfig(html) {
  const m = html.match(/tailwind\.config\s*=\s*(\{[\s\S]*?\})\s*;?\s*<\/script>/);
  if (!m) return null;
  // The config is a JS object literal; evaluate it in an isolated function scope.
  return new Function(`return (${m[1]});`)();
}

const toPx = (v) => {
  if (typeof v !== 'string') return v;
  if (v.endsWith('rem')) return parseFloat(v) * REM;
  if (v.endsWith('px')) return parseFloat(v);
  return parseFloat(v);
};

// Stable JSON with sorted keys, so key order in the exported HTML doesn't matter.
const canon = (v) =>
  v && typeof v === 'object' && !Array.isArray(v)
    ? `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canon(v[k])}`).join(',')}}`
    : JSON.stringify(v);

const configs = [];
for (const slug of readdirSync(screensDir).sort()) {
  const cfg = extractConfig(readFileSync(join(screensDir, slug, 'index.html'), 'utf8'));
  if (cfg) configs.push({ slug, ext: cfg.theme.extend });
}

// Pick the most common value of each section independently.
function majority(section) {
  const counts = new Map();
  for (const { slug, ext } of configs) {
    const key = canon(ext[section]);
    if (!counts.has(key)) counts.set(key, { value: ext[section], screens: [] });
    counts.get(key).screens.push(slug);
  }
  return [...counts.values()].sort((a, b) => b.screens.length - a.screens.length);
}

const colorGroups = majority('colors');
const ext = {
  colors: colorGroups[0].value,
  borderRadius: majority('borderRadius')[0].value,
  spacing: majority('spacing')[0].value,
  fontSize: majority('fontSize')[0].value,
};
const screens = colorGroups[0].screens;
const groups = colorGroups.map((g) => ({ ext: { colors: g.value }, screens: g.screens }));

const colors = Object.fromEntries(
  Object.entries(ext.colors).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => [k, v.toLowerCase()]),
);

const radius = Object.fromEntries(
  Object.entries({ ...TAILWIND_RADIUS, ...ext.borderRadius }).map(([k, v]) => [k, toPx(v)]),
);

const spacing = Object.fromEntries(Object.entries(ext.spacing).map(([k, v]) => [k, toPx(v)]));

const typography = Object.fromEntries(
  Object.entries(ext.fontSize).map(([name, [size, opts]]) => {
    const fontSize = toPx(size);
    const ls = opts.letterSpacing.endsWith('em') ? parseFloat(opts.letterSpacing) * fontSize : toPx(opts.letterSpacing);
    return [name, {
      fontSize,
      lineHeight: toPx(opts.lineHeight),
      letterSpacing: Math.round(ls * 100) / 100,
      fontWeight: opts.fontWeight,
    }];
  }),
);

const variants = groups.slice(1).map((g) => {
  const diff = Object.fromEntries(
    Object.entries(g.ext.colors)
      .filter(([k, v]) => colors[k] !== v.toLowerCase())
      .map(([k, v]) => [k, v.toLowerCase()]),
  );
  return { screens: g.screens, colors: diff };
});

const banner = `// AUTO-GENERATED by scripts/sync-stitch-tokens.mjs from design/stitch/screens.
// Do not edit by hand. Re-run the script after re-exporting Stitch screens.
//
// Canonical config shared by ${screens.length} screens.`;

const out = `${banner}

export const stitchColors = ${JSON.stringify(colors, null, 2)} as const;

/** Border radius in px (Stitch overrides merged onto Tailwind defaults). */
export const stitchRadius = ${JSON.stringify(radius, null, 2)} as const;

/** Named spacing in px. Numeric Tailwind steps (gap-2 etc.) are n * 4px. */
export const stitchSpacing = ${JSON.stringify(spacing, null, 2)} as const;

/** Type scale in px; letterSpacing converted from em. */
export const stitchTypography = ${JSON.stringify(typography, null, 2)} as const;

/** Screens whose embedded config diverges from the canonical one. */
export const stitchVariants = ${JSON.stringify(variants, null, 2)} as const;
`;
writeFileSync(outFile, out);
console.log(`Wrote ${outFile}: canonical from ${screens.length} screens, ${variants.length} variant group(s).`);
